#!/usr/bin/env node
/**
 * Writes docs/assets/contact-sheet.md: every delivered image as a 96 px thumbnail with its registry
 * id and file name, grouped by folder. Built from the files on disk (PNG and SVG; a WebP copy next
 * to a PNG is not shown twice) plus the ids in the group manifests
 * (public/art/mockup/<group>/manifest.json). A file with no id shows "no id".
 *
 *   node scripts/art/generate-contact-sheet.mjs          # write the file
 *   node scripts/art/generate-contact-sheet.mjs --check  # exit 1 when the file is out of date
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(fileURLToPath(import.meta.url), "..", "..", "..");
const PUBLIC = join(ROOT, "public");
const OUT = join(ROOT, "docs", "assets", "contact-sheet.md");
const posix = (p) => p.split(sep).join("/");

function walk(dir, out = []) {
  if (!existsSync(dir)) return out;
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

// Ids from the group manifests, by public URL.
const ids = new Map();
const mockup = join(PUBLIC, "art", "mockup");
for (const g of existsSync(mockup) ? readdirSync(mockup) : []) {
  const m = join(mockup, g, "manifest.json");
  if (!existsSync(m)) continue;
  for (const a of JSON.parse(readFileSync(m, "utf8"))) ids.set(a.file, a.key);
}

const images = ["art", "brand", "icons"]
  .flatMap((d) => walk(join(PUBLIC, d)))
  .filter((p) => /\.(png|svg)$/.test(p));

const byFolder = new Map();
for (const p of images) {
  const folder = posix(relative(PUBLIC, dirname(p)));
  (byFolder.get(folder) ?? byFolder.set(folder, []).get(folder)).push(p);
}

const lines = [
  "# SwimQuest asset contact sheet",
  "",
  "<!-- Generated by `node scripts/art/generate-contact-sheet.mjs`. Do not edit by hand. -->",
  "",
  "Every delivered image as a 96 px thumbnail, grouped by folder, with its registry id and file",
  'name. A file without a registry id shows "no id". Regenerate with',
  "`node scripts/art/generate-contact-sheet.mjs`.",
  "",
  `Images: ${images.length} in ${byFolder.size} folders.`,
];
for (const [folder, list] of [...byFolder].sort((a, b) => a[0].localeCompare(b[0]))) {
  lines.push("", `## ${folder}`, "", `${list.length} images.`, "");
  lines.push("| Thumbnail | Id | File |", "|---|---|---|");
  for (const p of list) {
    const url = `/${posix(relative(PUBLIC, p))}`;
    const rel = posix(relative(dirname(OUT), p));
    const name = url.split("/").pop();
    lines.push(
      `| <img src="${rel}" width="96" alt="${name}"> | ${ids.get(url) ?? "no id"} | \`${name}\` |`,
    );
  }
}
const text = lines.join("\n") + "\n";

if (process.argv.includes("--check")) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (current !== text) {
    console.error("docs/assets/contact-sheet.md is out of date: run the script.");
    process.exit(1);
  }
} else {
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, text);
  console.log(`wrote ${posix(relative(ROOT, OUT))} (${images.length} images)`);
}
